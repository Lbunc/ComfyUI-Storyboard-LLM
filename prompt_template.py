# -*- coding: utf-8 -*-
"""
ComfyUI-Storyboard-LLM 插件 - 提示词模板模块

本模块定义了用于生成分镜表的提示词模板,包括:
1. 默认提示词模板(包含详细的分镜生成规则)
2. 提示词格式化函数(将章节内容插入模板)

提示词模板的作用:
- 指导 DeepSeek 模型如何将小说文本转化为分镜表
- 定义输出格式(JSON 数组)
- 提供示例帮助模型理解期望的输出
"""

# 默认提示词模板
DEFAULT_PROMPT_TEMPLATE = """你是一位资深影视分镜师,擅长将文学性小说转化为可执行的视觉分镜脚本.

【输出要求】
请按叙事顺序切分为连续镜头,每个镜头输出三段内容:

**第一段 - 静态分镜提示词**:按"人物(具体名称)+动作/姿势+场景环境+光线描述+构图(景别+角度+焦段)"的顺序,用自然语言写成一句完整描述.不添加时间或动态词汇,聚焦于单帧画面.

**第二段 - 动态视频提示词**:按以下模板自然语言输出--
"[人物/主体名称] 正在 [做什么动作],它的 [局部细节] 随之 [如何运动].周围环境中的 [元素] 在 [如何变化],光影 [如何转变].镜头 [如何移动]."

**第三段 - 台词**:该镜头中人物说出的台词,若为内心独白则标注"(内心独白)",无台词则写"无".

【格式格式】
以JSON数组输出,每个镜头对象包含三个字段:`"静态"`,`"动态"`,`"台词"`.

【示例】
[
    {
        "静态": "一名黑色短发的青年男子,身穿破旧灰色风衣,背对镜头,右手握长刀刀尖点地,微微喘息,身处雨夜小巷,青石板路积水反射微光,两侧是斑驳砖墙.顶侧光来自巷口昏暗路灯,冷白硬光,高反差,人物轮廓被勾亮.全景,低角度仰视,24mm广角.",
        "动态": "青年男子正在微微喘息,破旧灰色风衣随风飘动.他的右手握长刀,刀尖点地,身体随呼吸轻微起伏.周围环境中的雨水滴落在青石板路上溅起细小水花,积水表面涟漪扩散.光影中路灯冷白光维持稳定,但人物面部阴影随喘息微动.镜头使用24mm广角镜头缓慢前推.",
        "台词": "无"
    },
    {
        "静态": "青年男子缓缓抬起头,雨水顺着脸颊滑落,眼神决绝.场景为雨夜小巷,青石板路积水反射微光.正面补入微弱暖光(来自刀身反射),主光为冷白顶侧光来自巷口路灯.近景,平视,85mm中长焦.",
        "动态": "青年男子正在缓缓抬起头,雨水顺着他的脸颊滑落.他的眼神变得决绝,嘴唇微抿.周围环境中的雨丝持续下落,地面上积水反光随他的头部移动略有变化.光影中冷白主光不变,刀身反射的暖光在画面一角保持稳定.镜头固定.",
        "台词": "(内心独白)这就是尽头了."
    }
]

【关键约束】
1. 每段都必须是自然语言描述,不要使用列表或符号.
2. 避免抽象词汇(如"悲伤的氛围"),转为具象动作与光线.
3. 相邻镜头的场景和光线应连贯,但不得写"同上".
4. 镜头数量根据内容节奏自然切分.

【章节内容】
{chapter_content}

【输出要求】
1. 直接返回JSON数组,不要包含任何解释说明文字
2. 确保JSON格式正确,可以被解析"""


def get_prompt_template():
    """
    获取默认提示词模板
    
    返回值:
        str: 默认提示词模板字符串
    
    用途:
        当用户没有提供自定义提示词时,使用此模板
    """
    return DEFAULT_PROMPT_TEMPLATE


def format_prompt(chapter_content: str) -> str:
    """
    格式化提示词(将章节内容插入模板)
    
    参数:
        chapter_content: str - 小说章节文本
    
    返回值:
        str: 格式化后的完整提示词
    
    注意:
        使用 replace() 而不是 format(),因为模板中包含 JSON 示例,
        JSON 示例中的花括号 {} 会被 format() 误认为是占位符
    """
    # 将章节内容替换到模板中的占位符位置
    return DEFAULT_PROMPT_TEMPLATE.replace("{chapter_content}", chapter_content)
